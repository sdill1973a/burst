#!/usr/bin/env python3
"""gen_exp_table.py — the two Q31 tables detrc.c uses for 2^-x, generated ONCE and pasted as constants.

detrc never calls libm: exp(-d) is computed as 2^-(d/ln2) = 2^-n * TA[a] * TB[b] / 2^62 where the fractional part of
d/ln2 (16 bits) splits into a (high 8 bits, steps of 1/256) and b (low 8 bits, steps of 1/65536). Both tables hold
round(2^31 * 2^-(k/N)). Run: python3 gen_exp_table.py > detrc_exptab.h
"""
from fractions import Fraction
from decimal import Decimal, getcontext

getcontext().prec = 50


def tab(N):
    out = []
    for k in range(256):
        v = Decimal(2) ** (Decimal(31) - Decimal(k) / Decimal(N))
        out.append(int(v.to_integral_value()))   # ROUND_HALF_EVEN; the constants are frozen in the header anyway
    return out


def emit(name, vals):
    print(f"static const uint64_t {name}[256] = {{")
    for i in range(0, 256, 6):
        print("    " + ", ".join(f"{v}ULL" for v in vals[i:i + 6]) + ",")
    print("};")


if __name__ == "__main__":
    print("/* generated by gen_exp_table.py — do not edit; round(2^31 * 2^-(k/256)) and round(2^31 * 2^-(k/65536)) */")
    print("#include <stdint.h>")
    emit("DETRC_TA", tab(256))
    emit("DETRC_TB", tab(65536))
